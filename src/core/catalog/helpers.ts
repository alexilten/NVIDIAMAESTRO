export const DUAL_SLOT = 40.64;

export const s = <T = number>(value: T | null, status: Verification, sourceId?: string, note?: string): Spec<T> => ({ value, status, sourceId, note });
export const dims = (w: Spec, d: Spec, h: Spec): Dimensions => ({ width: w, depth: d, height: h });
export const unknownDims = (): Dimensions => dims(s<number>(null, 'placeholder'), s<number>(null, 'placeholder'), s<number>(null, 'placeholder'));

export function proxy(id: string, lod: 0 | 1, provenance: string) {
  return { id, kind: 'procedural-proxy' as const, lod, label: lod === 0 ? 'Envelope' : 'Generated proxy', provenance: `${provenance} Generated by MAESTRO from the recorded dimensions; not manufacturer geometry.`, version: 1, createdAt: REVIEWED };
}
